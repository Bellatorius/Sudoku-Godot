def big_bot():
    """24x24 Nine Bot with 2-pixel strokes."""
    g = [["."] * 24 for _ in range(24)]
    def put(c0, c1, r0, r1, ch="#"):
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                g[r][c] = ch
    put(11, 12, 2, 3, "+"); put(11, 12, 4, 5)            # antenna light + stem
    put(4, 7, 10, 13)                                    # left eye
    put(14, 19, 9, 14); put(16, 17, 11, 12, ".")         # the 9's head (2-px ring)
    g[9][14] = g[9][19] = g[14][14] = "."                # soften the ring corners
    put(18, 19, 15, 18)                                  # tail
    put(5, 18, 19, 19); put(6, 17, 20, 20)               # mouth
    put(4, 5, 16, 18); g[19][5] = "#"                    # left end of the smile
    g[19][18] = "."
    return "\n".join("".join(r) for r in g)


def parse(art):
    if art is None:
        art = big_bot()
    rows = [r for r in art.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".") for r in rows]


def rects(rows, ox, oy, p, main, accent):
    out = []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in "#+":
                out.append(f'<rect x="{ox + x * p}" y="{oy + y * p}" width="{p}" height="{p}" '
                           f'fill="{main if ch == "#" else accent}"/>')
    return "".join(out)


def bounds(rows):
    xs = [x for row in rows for x, ch in enumerate(row) if ch in "#+"]
    ys = [y for y, row in enumerate(rows) if any(ch in "#+" for ch in row)]
    return min(xs), min(ys), max(xs) + 1, max(ys) + 1


def placed(rows, box, main, accent):
    """Sprite at the biggest whole-pixel scale that fits `box`, centred on its own ink in the 256 canvas."""
    x0, y0, x1, y1 = bounds(rows)
    p = int(box // max(x1 - x0, y1 - y0))
    ox = round(128 - (x0 + x1) * p / 2)
    oy = round(128 - (y0 + y1) * p / 2)
    return f'<g shape-rendering="crispEdges">{rects(rows, ox, oy, p, main, accent)}</g>'


def svg(w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img"><title>{title}</title>{body}</svg>\n')


def tile(c):
    return f'<rect x="12" y="12" width="232" height="232" rx="56" fill="{c}"/>'


STYLES = [
    ("a", lambda r: placed(r, 200, INK, INK)),
    ("b", lambda r: '<rect x="18" y="18" width="220" height="220" rx="48" fill="none" stroke="#0e0e12" stroke-width="14"/>'
                    + placed(r, 150, INK, INK)),
    ("c", lambda r: tile(INK) + placed(r, 160, WHITE, GOLD)),
    ("d", lambda r: tile(ACCENT) + placed(r, 160, WHITE, GOLD)),
    ("e", lambda r: f'<circle cx="128" cy="128" r="118" fill="{GOLD}"/>' + placed(r, 140, INK, WHITE)),
]

index = []
for i, (name, note, art) in enumerate(SPRITES):
    rows = parse(art)
    num = i + 1
    for code, st in STYLES:
        open(f"{OUT}/{num:03d}{code}-{VER}.svg", "w").write(svg(256, 256, st(rows), f"{name} {code}"))
    w, h = len(rows[0]), len(rows)
    nat = f'<rect width="{w}" height="{h}" fill="{INK}"/><g shape-rendering="crispEdges">{rects(rows, 0, 0, 1, WHITE, GOLD)}</g>'
    open(f"{OUT}/{num:03d}n-{VER}.svg", "w").write(svg(w, h, nat, f"{name} native"))
    index.append(f"{num}\t{name}\t{note}\t{w}\t{h}")
open(f"{OUT}/index.txt", "w", encoding="utf-8").write("\n".join(index))
